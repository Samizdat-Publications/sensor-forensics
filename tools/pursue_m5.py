def fdir(clip: str) -> Path:
    return ROOT / "data" / "frames" / clip.lower()


def frame(clip: str, f: int) -> np.ndarray:
    return cv2.imread(str(fdir(clip) / f"f{f:06d}.png"))


def write_csv(path: Path, rows: list[dict]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)


def read_csv(path: Path) -> list[dict]:
    with path.open(encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


# ---------------------------------------------------------------------------
# PR113: ladder sweep
# ---------------------------------------------------------------------------

def pr113_sweep() -> None:
    clip = "DOW-UAP-PR113"
    n = len(list(fdir(clip).glob("f*.png")))
    rows = []
    for f in range(0, min(n, 4000), 15):
        im = frame(clip, f)
        a = ladder_profile_fit(im)
        b = ladder_profile_fit(im, exclude_small_roll=3.0)
        rows.append({"frame": f, "t_s": f"{f / 30:.3f}",
                     "angle_deg": f"{a['angle_deg']:.2f}", "spacing_px": f"{a['spacing_px']:.2f}",
                     "quality": f"{a['quality']:.3f}",
                     "angle_deg_rolled": f"{b['angle_deg']:.2f}",
                     "spacing_px_rolled": f"{b['spacing_px']:.2f}",
                     "quality_rolled": f"{b['quality']:.3f}"})
    write_csv(DER / clip.lower() / "ladder_auto.csv", rows)
    print(f"{clip}: {len(rows)} sampled frames")


# ---------------------------------------------------------------------------
# PR149: object track and ship drift
# ---------------------------------------------------------------------------

def pr149_track() -> None:
    clip = "DOW-UAP-PR149"
    gray = {}

    def g(f: int) -> np.ndarray:
        if f not in gray:
            gray[f] = cv2.cvtColor(frame(clip, f), cv2.COLOR_BGR2GRAY)
        return gray[f]

    # Seed path: coarse detections by mover_peak over the whole frame (frames 16, 32, 78, 96).
    seed_f, seed_x, seed_y = [16, 32, 78, 96], [1643, 1339, 401, 40], [894, 846, 710, 665]
    cx, cy = np.polyfit(seed_f, seed_x, 1), np.polyfit(seed_f, seed_y, 1)
    rows, prev_xy = [], None
    for f in range(14, 98):
        px, py = np.polyval(cx, f), np.polyval(cy, f)
        valid = np.zeros(g(f).shape, bool)
        valid[int(py) - 25:int(py) + 25, max(0, int(px) - 40):int(px) + 40] = True
        x, y, s = mover_peak(g(f - 3), g(f), g(f + 3), valid)
        b = blob_centroid(g(f), (x, y), r=12)
        if b is None or s < 50:
            continue
        dup = prev_xy is not None and abs(b[0] - prev_xy[0]) < 0.05 and abs(b[1] - prev_xy[1]) < 0.05
        prev_xy = b[:2]
        rows.append({"frame": f, "x": f"{b[0]:.2f}", "y": f"{b[1]:.2f}", "ext_x": b[2], "ext_y": b[3],
                     "npix": b[4], "score": f"{s:.0f}", "repeat_of_previous": int(dup)})
    # ship: waterline extent and position (largest bright component, blurred > 170)
    ship = []
    for f in range(0, 110, 2):
        m = (cv2.GaussianBlur(g(f), (5, 5), 0) > 170).astype(np.uint8)
        n, lab, st, cen = cv2.connectedComponentsWithStats(m)
        i = 1 + int(np.argmax(st[1:, 4]))
        ys, xs = np.nonzero(lab == i)
        pts = np.c_[xs, ys].astype(float)
        mu = pts.mean(0)
        _, _, vt = np.linalg.svd(pts - mu, full_matrices=False)
        pr = (pts - mu) @ vt[0]
        ship.append({"frame": f, "x0": int(xs.min()), "x1": int(xs.max()), "cx": f"{mu[0]:.2f}",
                     "cy": f"{mu[1]:.2f}", "axis_len_px": f"{pr.max() - pr.min():.1f}"})
    write_csv(DER / clip.lower() / "object_track.csv", rows)
    write_csv(DER / clip.lower() / "ship_track.csv", ship)
    print(f"{clip}: {len(rows)} object points, {len(ship)} ship samples")


